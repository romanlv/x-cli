// bun core/workflows/prompts-doc.ts <cli name> <domain folder> <out.md>
//
// docs/prompts.md: every prompt in prompts.ts filled in for a sample request, in the order a run
// sends them, with who gets each. A test fails when it is out of date.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import * as prompts from "../instructions/prompts";
import type { RequestRecord } from "../requests";
import { loadConfig, type Role, type WorkflowConfig } from "./config";
import type { Verified } from "./deps";
import { sandboxPaths } from "./sandbox";
import { LIMITS, pathsFor } from "./shared";

const ROOT = "/repo";

const fence = (text: string): string => `\`\`\`\`text\n${text}\n\`\`\`\``;

const model = (config: WorkflowConfig, role: Role): string => {
  const runtime = config.agents[role];
  return typeof runtime === "object" ? Object.values(runtime).join(" · ") : String(runtime);
};

export const renderPrompts = (cli: string, domainFolder: string, config: WorkflowConfig): string => {
  const request: RequestRecord = {
    id: "R-0001",
    kind: "new",
    text: "the things that match a word, newest first",
    context: "acme",
    domain: { name: cli, root: ROOT, dir: join(ROOT, domainFolder), home: join(ROOT, ".state") },
    call: { op: "thing:find", argv: ["thing:find", "--query", "lamp"] },
    state: "building",
    createdAt: "2026-01-01T00:00:00.000Z",
    updatedAt: "2026-01-01T00:00:00.000Z",
    answers: [],
    attempts: 1,
  };
  const runFor = (r: RequestRecord) => ({ request: r, paths: pathsFor(r, { ...config, sandbox: false }) });
  const run = runFor(request);
  // /tmp as given, not by its real path, so the doc is the same on every machine.
  const sandboxed = { request, paths: pathsFor(request, config, sandboxPaths(request, "/tmp")) };
  const answered = {
    ...run,
    request: {
      ...request,
      answers: [{ at: request.createdAt, question: "Should archived things be left out?", text: "Yes, only current ones." }],
    },
  };
  const op = "thing:find";
  const plan = "List the things that match the query, newest first, with their name, time and link.";
  const failure = { step: "open search", error: "timeout at read results", bundle: join(ROOT, ".state/failures/F-1") };
  const repair = runFor({
    ...request,
    id: "R-0002",
    kind: "repair",
    // As the runner files it.
    text: `${op} failed at "${failure.step}": ${failure.error}`,
    op,
    failure,
  });
  const other: RequestRecord = {
    ...request,
    id: "R-0003",
    text: "one thing and what links to it",
    op: "thing:show",
    call: undefined,
  };
  const verify = (error?: string): Verified[] => [
    {
      op,
      ok: !error,
      signedOut: false,
      noExamples: false,
      runs: [{ input: { query: "lamp" }, ok: !error, exitCode: error ? 1 : 0, error }],
    },
  ];
  const problems = [
    prompts.verifyFailed(request, verify("timeout at read results")),
    prompts.checksFailed(run, "fast", `${domainFolder}/ops/thing-find/op.ts:12: Code style issues found`),
    prompts.reviewFound([{ where: "op.ts:30", problem: "the output echoes the input", severity: "blocking" }]),
    prompts.reviewFound([{ where: "spec.md:3", problem: "names the wrong sort order", severity: "blocking" }]),
  ];
  const minor = [{ where: "notes.md:4", problem: "a typo in the screen name", severity: "minor" as const }];

  const section = (title: string, who: string, text: string) => `### ${title}\n\n${who}\n\n${fence(text)}\n`;
  return [
    "<!-- Generated by `bun run docs:prompts` from core/instructions/prompts.ts. Don't edit; a test fails when it is out of date. -->",
    "# Prompts",
    "",
    `Every prompt the build and repair workflows send, filled in for a sample request: ${request.id} asks for a new op, ${op}, filed by a call in context "${request.context}". Paths are under ${ROOT}, agents run unsandboxed (\`workflows.json\` ${config.sandbox ? "turns the sandbox on in this checkout" : "can turn the sandbox on"}: [In a sandbox](#in-a-sandbox) has what changes then), and no one has answered a question yet, except where a prompt says otherwise. Each prompt is a function in \`core/instructions/prompts.ts\`; the workflows (\`build.ts\`, \`repair.ts\`, \`shared.ts\`) decide when it is sent and to whom.`,
    "",
    "What isn't here is read by the agents from the domain folder: how an op is written for this app (`authoring.md`, after `core/instructions/authoring.md`) and what the app and each context are like (`knowledge/`).",
    "",
    "## Agents",
    "",
    "Each agent's model is its default in `core/workflows/config.ts`, or the one `workflows.json` names where it differs.",
    "",
    "| Agent | Model | Instructions | Stages |",
    "|---|---|---|---|",
    `| planner | ${model(config, "planner")} | planner | intake, spec (after explore) |`,
    `| builder | ${model(config, "builder")} | builder | explore, write, diagnose, patch, revise while each round gets further, polish, rebase |`,
    `| checker | ${model(config, "checker")} | checker | review |`,
    `| troubleshooter | ${model(config, "troubleshooter")} | builder | revise once the builder's rounds stop getting further, polish after that, the final question |`,
    "",
    "## Instructions",
    "",
    "Each agent gets these once, when it is opened.",
    "",
    section("Planner", "The planner.", prompts.plannerInstructions(run)),
    section("Builder", "The builder and the troubleshooter.", prompts.builderInstructions(run)),
    section("Checker", "The checker.", prompts.checkerInstructions(run)),
    "## Build",
    "",
    section(
      "intake",
      `The planner, one request at a time. It answers build, duplicate, same, deferred or declined; here with ${other.id} open.`,
      prompts.intake(run, [other], false),
    ),
    section(
      "explore",
      "The builder. It answers done, missing (the request ends deferred) or a question.",
      prompts.explore(run, op, plan, false),
    ),
    section(
      "spec",
      "The planner, after explore.",
      prompts.spec(run, op, plan, false, "Search for the query and sort by newest: the results list the matching things, newest first."),
    ),
    section("write", "The builder.", prompts.write(run, op, plan)),
    "## Repair",
    "",
    "Filed by the runner when an op failed; there is no intake. The request in the brief is the failure, as the runner filed it.",
    "",
    section("diagnose", "The builder. It answers reproduced or flaky.", prompts.diagnose(repair, op, failure)),
    section("patch", "The builder.", prompts.patch(repair, op, failure, "The sort control is now a menu.")),
    "## Check",
    "",
    "Verify and the repository's checks run first; what fails becomes the next revise's problem, with no review.",
    "",
    section("review", "The checker, once verify and the checks pass.", prompts.review(run, op, plan, verify())),
    section(
      "revise",
      "The builder, for as long as each round gets further than the one before: a later check, or fewer problems. The problem is what verify, the checks or the review found.",
      prompts.revise(run, op, plan, problems.slice(0, 1)),
    ),
    section(
      "revise, taking over",
      "The troubleshooter, once a builder round got no further, with every earlier round's problem; its later rounds get the plain revise.",
      prompts.revise(run, op, plan, problems, 3),
    ),
    section(
      "polish",
      "Whoever has the rounds, when the review found only minor problems. Nobody reviews it after.",
      prompts.polish(run, op, plan, minor),
    ),
    section(
      "question",
      `The troubleshooter, once one of its rounds got no further, or after round ${LIMITS.rounds}; the run blocks on its answer.`,
      prompts.stuck(run, op, plan, problems),
    ),
    "## Merge",
    "",
    section("rebase", "The builder, when rebasing on main conflicts.", prompts.rebase(run, op, plan, `${domainFolder}/helpers/index.ts`)),
    "## Any turn",
    "",
    section(
      "signed in again",
      `Sent in the same turn after an agent answered "sign in again", when the run signed in from \`.env.${request.context}\`.`,
      prompts.signedInAgain(request),
    ),
    section(
      "earlier answers",
      "Appended to most prompts once a person has answered a question; here, explore's. Review's, polish's, rebase's and the question's say only to follow the answers: review and the question change no files, and polish and rebase only what they ask for.",
      prompts.explore(answered, op, plan, false),
    ),
    "## In a sandbox",
    "",
    `With the sandbox on, agents keep their CLI state in ${sandboxed.paths.sandbox!.home} and reach the host's browser through a socket in ${sandboxed.paths.sandbox!.sockets}. Every prompt and instruction that names the CLI names it as:`,
    "",
    fence(sandboxed.paths.cli),
    "",
    section(
      "write",
      "The trace is in the sandbox's home, and the last steps, which patch and revise end with too, run `ci:sandbox` with the browser's socket.",
      prompts.write(sandboxed, op, plan),
    ),
    section(
      "checks failed",
      "A revise's problem when the repository's checks fail: the agent reruns what its sandbox can.",
      prompts.checksFailed(sandboxed, "fast", `${domainFolder}/ops/thing-find/op.ts:12: Code style issues found`),
    ),
  ].join("\n");
};

if (import.meta.main) {
  const [cli, folder, out] = process.argv.slice(2);
  if (!cli || !folder || !out) throw new Error("usage: prompts-doc.ts <cli name> <domain folder> <out.md>");
  writeFileSync(out, renderPrompts(cli, folder, loadConfig(process.cwd())));
}
